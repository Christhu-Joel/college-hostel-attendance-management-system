-- -------------------------------------------------------------
-- academic_years
-- Stores academic year periods. One year can be active at a time.
-- Old years are archived (never deleted) to preserve attendance.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS academic_years (
  id         INT UNSIGNED     NOT NULL AUTO_INCREMENT,
  year_name  VARCHAR(20)      NOT NULL,
  is_active  TINYINT(1)       NOT NULL DEFAULT 0,
  created_at TIMESTAMP        NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_academic_years_name (year_name)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- rooms
-- A hostel room with a fixed capacity. current_strength is kept
-- in sync by the application layer when students move in/out.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rooms (
  id              INT UNSIGNED NOT NULL AUTO_INCREMENT,
  room_number     VARCHAR(20)  NOT NULL,
  capacity        INT UNSIGNED NOT NULL DEFAULT 2,
  current_strength INT UNSIGNED NOT NULL DEFAULT 0,
  created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_rooms_number (room_number),
  CONSTRAINT chk_rooms_capacity CHECK (capacity >= 1),
  CONSTRAINT chk_rooms_strength CHECK (current_strength >= 0)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- students
-- Hostel residents. A student may be unassigned (room_id NULL).
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS students (
  id          INT UNSIGNED  NOT NULL AUTO_INCREMENT,
  register_no VARCHAR(30)   NOT NULL,
  name        VARCHAR(100)  NOT NULL,
  category    ENUM('UG','PG') NOT NULL,
  department  VARCHAR(100)  NOT NULL,
  study_year  TINYINT UNSIGNED NOT NULL,
  room_id     INT UNSIGNED  NULL,
  status      ENUM('active','inactive') NOT NULL DEFAULT 'active',
  created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_students_register (register_no),
  KEY idx_students_name (name),
  KEY idx_students_category (category),
  KEY idx_students_department (department),
  KEY idx_students_study_year (study_year),
  KEY idx_students_room (room_id),
  KEY idx_students_status (status),
  CONSTRAINT fk_students_room FOREIGN KEY (room_id)
    REFERENCES rooms (id) ON DELETE SET NULL,
  CONSTRAINT chk_students_study_year CHECK (study_year BETWEEN 1 AND 6)
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- attendance
-- One record per student per day (unique constraint enforces the
-- "recorded once per day" business rule). The active academic year
-- at marking time is stored so records can be filtered by year.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS attendance (
  id                INT UNSIGNED NOT NULL AUTO_INCREMENT,
  student_id        INT UNSIGNED NOT NULL,
  attendance_date   DATE         NOT NULL,
  status            ENUM('present','absent') NOT NULL,
  academic_year_id  INT UNSIGNED NULL,
  marked_at         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_attendance_student_date (student_id, attendance_date),
  KEY idx_attendance_date (attendance_date),
  KEY idx_attendance_status (status),
  KEY idx_attendance_academic_year (academic_year_id),
  CONSTRAINT fk_attendance_student FOREIGN KEY (student_id)
    REFERENCES students (id) ON DELETE CASCADE,
  CONSTRAINT fk_attendance_academic_year FOREIGN KEY (academic_year_id)
    REFERENCES academic_years (id) ON DELETE SET NULL
) ENGINE=InnoDB;

-- -------------------------------------------------------------
-- users
-- Login accounts for the warden. Passwords are stored as a
-- salted scrypt hash (salt:hash), never in plain text.
-- -------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  username      VARCHAR(50)  NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(20)  NOT NULL DEFAULT 'warden',
  created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_username (username)
) ENGINE=InnoDB;

